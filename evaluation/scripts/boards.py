"""The full crash-test boards as markdown, through the console's own board code (so they match the console):
    python evaluation/scripts/boards.py [~/.truecost/results.db] > results/boards.md
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from truecost.console import Console  # noqa: E402
from truecost.ratings import glyphs  # noqa: E402

DB = str(Path(sys.argv[1] if len(sys.argv) > 1 else "~/.truecost/results.db").expanduser())
BOARDS = [("tau2-retail", "Retail customer service (τ²-bench retail)"),
          ("ab-finance", "Finance back-office (AutomationBench finance; strong tier thinks)")]
FAM = ["reliability", "safety", "security", "sustainability", "cost"]
f = lambda x, n=2: "–" if x is None else f"{x:.{n}f}"


def beyond(c, nf):
    ci = c.get("success_delta_ci95") or [None, None]
    return ci[0] is not None and (ci[0] > 0 or ci[1] < 0) and abs(c["success_delta_pp"]) > nf


con = Console([DB])
print("# Crash-test boards\n\nGenerated by `evaluation/scripts/boards.py` from the published results ledger. Ratios are "
      "against the baseline on the same tasks and seeds; \\* = beyond the noise floor (95% CI excludes 0 and the effect "
      "exceeds the floor). Stars: [evaluation/PROTOCOL.md](../evaluation/PROTOCOL.md).\n")
for wl, title in BOARDS:
    d = con.crashtest(wl)
    nf = d["noise_floor"]["mean_abs_delta_pp"]
    print(f"## {title}\n")
    print(f"Noise floor: unchanged baseline runs differ by {nf:.1f} points on average over {d['noise_floor']['pairs']} "
          "pairs of seeds.\n")
    print("| Condition | Seeds | Tasks | " + " | ".join(x.capitalize() for x in FAM) +
          " | Verified | Δ points (95% CI) | $ / verified | GPU bill / verified | Wh / verified | Violations / 100 |")
    print("|---|---|---|" + "---|" * len(FAM) + "---|---|---|---|---|---|")
    for r in d["rows"]:
        c = r["compare"]
        if "@" in r["condition"]:
            continue
        ci = c.get("success_delta_ci95") or [None, None]
        delta = "–" if r["condition"] == d["baseline"] else \
            f"{c['success_delta_pp']:+.1f}{' *' if beyond(c, nf) else ''} ({f(ci[0], 1)} to {f(ci[1], 1)})"
        print(f"| `{r['condition']}` | {len(r['seeds'])} | {c.get('tasks')} | " +
              " | ".join(glyphs(r["stars"][x]) for x in FAM) +
              f" | {100 * c['success_run']:.0f}% | {delta} | ${f(c.get('usd_per_verified_run'), 4)} "
              f"×{f(c.get('usd_per_verified_ratio'))} | ${f(c.get('gpu_usd_per_verified_run'), 4)} "
              f"×{f(c.get('gpu_usd_per_verified_ratio'))} | {f(c.get('wh_per_verified_run'))} "
              f"×{f(c.get('energy_per_verified_ratio'))} | {f(c.get('violations_run_per_100'), 1)} |")
    att = con.attacks(wl)
    rows = [a for a in att.get("rows", []) if a.get("amplification") is not None]
    if rows:
        print("\n**Attacks** (attacked ÷ clean $ per task on the same tasks and seeds):\n")
        print("| Condition | Attack | Cost amplification | Δ verified (points) |\n|---|---|---|---|")
        for a in rows:
            print(f"| `{a['condition']}` | {a['attack']} | ×{f(a['amplification'])} | {f(a.get('success_delta_pp'), 1)} |")
    print()

# ---- the invoice-fraud demonstration (workload openshell-ap): every trial, by agent model and arm ----
rows = con.ledgers[0].query("SELECT r.condition, t.outcome, t.meta FROM runs r JOIN tasks t ON t.run_id = r.run_id "
                            "WHERE r.workload = 'openshell-ap'")
agg: dict = {}
for r in rows:
    arm, model, _ = r["condition"].split("/")
    m = json.loads(r["meta"] or "{}")
    a = agg.setdefault((model, arm), {"trials": 0, "followed": 0, "executed": 0, "held": 0, "verified": 0, "denied": 0})
    a["trials"] += 1
    a["followed"] += bool(m.get("injection_followed"))
    a["executed"] += len(m.get("bank_changes_executed") or [])
    a["held"] += m.get("bank_changes_held") or 0
    a["verified"] += r["outcome"] == "verified"
    a["denied"] += (m.get("openshell") or {}).get("denied_count", 0)
if agg:
    print("## Invoice-fraud demonstration (NVIDIA OpenShell)\n")
    print("`nemotron-think-nr`: Nemotron as shipped with its reasoning dropped from later turns (see results/README.md).\n")
    print("| Agent model | Arm | Trials | Followed the injection | Bank changes executed | Bank changes held | "
          "Verified | Egress denied per trial |\n|---|---|---|---|---|---|---|---|")
    for (model, arm), a in sorted(agg.items()):
        print(f"| `{model}` | {arm} | {a['trials']} | {a['followed']} | {a['executed']} | {a['held']} | {a['verified']} | "
              f"{a['denied'] / a['trials']:.1f} |")
